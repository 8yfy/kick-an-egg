# DEV ONLY: converts the original Kick Sack GLBs (assets/sacks/glb/*.glb) into Luau data modules
# (tools/sacks/standin/TierNN.luau) that tools/preview builds into MeshParts with EditableMesh, so the GLB
# geometry can be checked in Studio BEFORE the GLBs are imported (Studio File > Import, tools/sacks/IMPORT.md).
# The game never uses this data: production geometry is the imported meshes.
#
#   blender -b --factory-startup --python tools/sacks/glb2luau.py -- assets/sacks/glb tools/sacks/standin
#
# Per GLB node (and material) one part: name = glTF node name, material = glTF material name, triangles in the
# glTF frame (metres, Y up, +Z front). Packed little-endian: float32 xyz per vertex, int8 xyz normal per vertex,
# uint16 triangle indices; base64 in a Luau string.
import base64, glob, os, struct, sys

import bpy
from mathutils import Vector

args = sys.argv[sys.argv.index("--") + 1 :]
src, out = args[0], args[1]
os.makedirs(out, exist_ok=True)


def to_gltf(v):  # Blender (x, y, z) Z-up -> glTF (x, z, -y) Y-up
    return (v[0], v[2], -v[1])


for path in sorted(glob.glob(os.path.join(src, "*.glb"))):
    tier = int(os.path.basename(path).split("-")[2])
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=path)
    dg = bpy.context.evaluated_depsgraph_get()
    blob = bytearray()
    parts = []
    for obj in sorted((o for o in bpy.context.scene.objects if o.type == "MESH"), key=lambda o: o.name):
        mesh = obj.evaluated_get(dg).to_mesh()
        mesh.calc_loop_triangles()
        m = obj.matrix_world
        nm = m.to_3x3().inverted().transposed()
        by_mat = {}
        for lt in mesh.loop_triangles:
            by_mat.setdefault(lt.material_index, []).append(lt)
        for mi, tris in sorted(by_mat.items()):
            mat = obj.material_slots[mi].material.name if mi < len(obj.material_slots) and obj.material_slots[mi].material else ""
            verts, norms, index, faces = [], [], {}, []
            for lt in tris:
                face = []
                for corner in range(3):
                    vi = lt.vertices[corner]
                    n = (nm @ Vector(lt.split_normals[corner])).normalized()
                    key = (vi, round(n.x, 2), round(n.y, 2), round(n.z, 2))
                    if key not in index:
                        index[key] = len(verts)
                        verts.append(to_gltf(m @ mesh.vertices[vi].co))
                        norms.append(to_gltf(n))
                    face.append(index[key])
                faces.append(face)
            if not faces or len(verts) > 65535:
                continue
            for v in verts:
                blob += struct.pack("<3f", *v)
            for n in norms:
                blob += struct.pack("<3b", *(max(-127, min(127, round(c * 127))) for c in n))
            for f in faces:
                blob += struct.pack("<3H", *f)
            name = obj.name.split(".")[0] if obj.name.count(".") == 1 and obj.name.split(".")[1].isdigit() else obj.name
            parts.append((name, mat.split(".")[0], len(verts), len(faces)))
        obj.evaluated_get(dg).to_mesh_clear()
    with open(os.path.join(out, f"Tier{tier:02d}.luau"), "w") as fh:
        fh.write(f"-- GENERATED by tools/sacks/glb2luau.py from {os.path.basename(path)}: DEV stand-in data, do not edit.\n")
        fh.write("return {\n\tparts = {\n")
        for p in parts:
            fh.write(f'\t\t{{ "{p[0]}", "{p[1]}", {p[2]}, {p[3]} }},\n')
        fh.write("\t},\n\tdata = \"" + base64.b64encode(bytes(blob)).decode() + "\",\n}\n")
    print(f"GLB2LUAU tier {tier}: {len(parts)} parts, {len(blob)} bytes")
